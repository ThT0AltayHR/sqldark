import json as _json
import os as _os
import re as _re_mod

def _load_signature_db():
    merged = {}
    sigdir = _os.path.join(_os.path.dirname(__file__), "signatures")
    db = {}
    if _os.path.isdir(sigdir):
        for fn in sorted(_os.listdir(sigdir)):
            if fn.endswith(".json"):
                try:
                    w = _json.load(open(_os.path.join(sigdir, fn), encoding="utf-8"))
                    db[w.get("id") or fn[:-5]] = w
                except Exception:
                    continue
    if not db:
        path = _os.path.join(_os.path.dirname(__file__), "signatures_db.json")
        try:
            db = _json.load(open(path, encoding="utf-8"))
        except Exception:
            return merged
    for key, w in db.items():
        name = w.get("name") or key
        rgx = w.get("regex")
        if not rgx:
            continue
        # Strip inline global flags like (?i) that are legal in PCRE but must sit
        # at the very start in Python; we already match case-insensitively.
        clean = _re_mod.sub(r"\(\?[aiLmsux]+\)", "", rgx)
        try:
            _re_mod.compile(clean, _re_mod.I)
        except _re_mod.error:
            continue  # skip signatures Python's re cannot parse
        # identYwaf regexes match response body or headers; try both.
        merged[name] = [("body", clean), ("header", clean)]
    return merged


class WafDetector:
    def __init__(self, http, log):
        self.http = http
        self.log = log
        self.signatures = dict(_load_signature_db())
        # Hand-tuned signatures take precedence (more precise header/cookie rules).
        self.signatures.update(SIGNATURES)

    def detect(self, point, baseline):
        resp = self._probe(point)
        candidates = []
        hdr_blob = " ".join(f"{k}: {v}" for k, v in resp.headers.items())
        server = resp.headers.get("Server", "")
        cookie = resp.headers.get("Set-Cookie", "")
        for name, sigs in self.signatures.items():
            for where, pat in sigs:
                hay = {"header": hdr_blob, "server": server, "cookie": cookie,
                       "body": resp.text, "status": str(resp.status)}[where]
                if _safe_search(pat, hay):
                    candidates.append(name)
                    break
        # Generic behavioural block: status jumped to 403/406/429/501
        blocked = resp.status in (403, 406, 429, 501, 999) and baseline.status not in (
            403, 406, 429, 501, 999)
        if candidates:
            name = candidates[0]
            self.log.warn(f"WAF/IPS identified: {name}")
            return {"detected": True, "name": name, "blocking": blocked}
        if blocked:
            self.log.warn(f"generic WAF/IPS behaviour (HTTP {resp.status} on probe)")
            return {"detected": True, "name": "generic", "blocking": True}
        self.log.info("no WAF/IPS fingerprinted")
        return {"detected": False, "name": None, "blocking": False}

    def _probe(self, point):
        url, data = point.build_raw(PROBE)
        return self.http.send(url, method=point.method, data=data)
